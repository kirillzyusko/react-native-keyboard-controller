// cspell:words swiftc swiftmodule mkdtemp xcrun cstdbool Warc nonarc modulemap
const { execFileSync } = require("child_process");
const fs = require("fs");
const os = require("os");
const path = require("path");

const root = path.resolve(__dirname, "..");
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), "rnkc-swift-header-"));

function xcrun(args, options = {}) {
  return execFileSync("xcrun", args, {
    cwd: root,
    encoding: "utf8",
    ...options,
  });
}

try {
  // The manifest discovers files, so its source list must be read again each time.
  const manifest = JSON.parse(
    xcrun([
      "swift",
      "package",
      "--manifest-cache",
      "none",
      "--scratch-path",
      path.join(temporary, "package"),
      "dump-package",
    ]),
  );
  const target = manifest.targets.find(
    ({ name }) => name === "react_native_keyboard_controller",
  );
  const helper = manifest.targets.find(
    ({ name }) => name === "KeyboardControllerObjC",
  );
  const ios = manifest.platforms.find(
    ({ platformName }) => platformName === "ios",
  );
  const sources = target.sources
    .filter(
      (source) =>
        !target.exclude.some(
          (excluded) =>
            source === excluded || source.startsWith(`${excluded}/`),
        ),
    )
    .sort()
    .map((source) => path.resolve(root, target.path, source));
  const defines = target.settings.flatMap(({ tool, kind }) =>
    tool === "swift" && kind.define ? ["-D", kind.define._0] : [],
  );
  // Match SwiftPM's automatic umbrella map for the Objective-C helper target.
  const helperHeaders = JSON.stringify(
    path.resolve(root, helper.path, helper.publicHeadersPath),
  );

  fs.writeFileSync(
    path.join(temporary, "module.modulemap"),
    `module ${helper.name} { umbrella ${helperHeaders} export * }\n`,
  );
  const headerPath = path.join(temporary, "KeyboardControllerSwift.h");
  const sdk = xcrun(["--sdk", "iphonesimulator", "--show-sdk-path"]).trim();

  xcrun(
    [
      "swiftc",
      "-emit-module",
      "-parse-as-library",
      "-module-name",
      target.name,
      "-swift-version",
      manifest.swiftLanguageVersions[0],
      "-target",
      `arm64-apple-ios${ios.version}-simulator`,
      "-sdk",
      sdk,
      "-D",
      "SWIFT_PACKAGE",
      ...defines,
      "-I",
      temporary,
      "-emit-objc-header-path",
      headerPath,
      "-emit-module-path",
      path.join(temporary, `${target.name}.swiftmodule`),
      ...sources,
    ],
    { stdio: "inherit" },
  );

  // Ignore compiler prologue differences that do not affect the interface.
  const declarations = fs
    .readFileSync(headerPath, "utf8")
    .replace(/^\/\/ Generated by Apple Swift version .*\n/, "")
    .replace(/^#include <cstdbool>\n/gm, "")
    .replace(
      /^#pragma clang diagnostic ignored "-Warc-bridge-casts-disallowed-in-nonarc"\n/gm,
      "",
    )
    .replace(/[ \t]+$/gm, "");
  const header = `// Generated by yarn generate-ios-spm-header. Do not edit.
// clang-format off
// cspell:disable
#pragma once

#if SWIFT_PACKAGE
#import <UIKit/UIKit.h>

${declarations}
#endif // SWIFT_PACKAGE
// clang-format on
`;

  fs.writeFileSync(path.join(root, "ios/KeyboardControllerSwift.h"), header);
} finally {
  fs.rmSync(temporary, { recursive: true, force: true });
}
